const dicts: Record<Language, Dict> = { tr, en };

export type Params = Record<string, string | number | null | undefined>;

export function translate(lang: Language, key: TKey, params?: Params): string {
  let s: string = dicts[lang]?.[key] ?? tr[key] ?? key;
  if (params) {
    s = s.replace(/\{(\w+)\}/g, (_, k: string) => {
      const v = params[k];
      return v === undefined || v === null ? "" : String(v);
    });
  }
  return s;
}

export function hasKey(key: string): key is TKey {
  return key in tr;
}

export function useT() {
  const lang = useApp((s) => s.data?.settings.language ?? "tr");
  return (key: TKey, params?: Params) => translate(lang, key, params);
}

export function currentLang(): Language {
  return useApp.getState().data?.settings.language ?? "tr";
}

export function t(key: TKey, params?: Params) {
  return translate(currentLang(), key, params);
}
